/**
 * The rule a user pastes into CLAUDE.md / AGENTS.md / .cursorrules so the agent
 * actually reads the system. Single source for this copy: `kernic context`
 * prints the lines, the MCP apply_to_project tool returns the one-liner, and
 * neither can drift away from the other.
 */
export function agentRuleLines(ds: DesignSystem, briefPath = `./${DESIGN_MD_FILE}`): string[] {
  return [
    `Visual design: follow ${briefPath} exactly (${ds.name}, vibe: ${ds.vibe}).`,
    "Use only its color, type, and radius tokens — never invent raw hex values.",
  ];
}

/** The same rule as one pasteable line. */
export function agentRule(ds: DesignSystem, briefPath = `./${DESIGN_MD_FILE}`): string {
  return agentRuleLines(ds, briefPath).join(" ");
}

/* ─────────────────────────── DTCG 2025.10 ─────────────────────────── */

/** A colour value: OKLCH components, plus the hex every older pipeline and Figma read. */
function colorValue(hex: string, alpha?: number) {
  return { colorSpace: "oklch", components: oklchComponents(hex), ...(alpha === undefined ? {} : { alpha }), hex };
}

function dtcgColor(hex: string) {
  return { $type: "color", $value: colorValue(hex) };
}

/** An alias to another token, `{group.token}` form. */
function dtcgAlias(type: string, path: string) {
  return { $type: type, $value: `{${path}}` };
}

/** `"0.25rem"` → `{ value: 0.25, unit: "rem" }`, the 2025.10 dimension shape. */
export function dtcgDimension(dimension: string) {
  const m = /^(-?\d*\.?\d+)(px|rem|em)$/.exec(dimension.trim());
  if (!m) throw new Error(`Not a dimension: "${dimension}". Expected a number with px, rem or em.`);
  return { $type: "dimension", $value: { value: Number(m[1]), unit: m[2] } };
}

/** `"200ms"` → `{ value: 200, unit: "ms" }`. */
export function dtcgDuration(duration: string) {
  const m = /^(\d*\.?\d+)(ms|s)$/.exec(duration.trim());
  if (!m) throw new Error(`Not a duration: "${duration}". Expected a number with ms or s.`);
  return { $type: "duration", $value: { value: Number(m[1]), unit: m[2] } };
}

function dtcgShadow(layers: ShadowLayer[]) {
  return {
    $type: "shadow",
    $value: layers.map((l) => ({
      color: colorValue(l.color, l.alpha),
      offsetX: dtcgDimension(l.x).$value,
      offsetY: dtcgDimension(l.y).$value,
      blur: dtcgDimension(l.blur).$value,
      spread: dtcgDimension(l.spread).$value,
    })),
  };
}

/**
 * W3C Design Tokens, Format Module 2025.10: colours as OKLCH objects with a
 * hex fallback, dimensions as value + unit, semantic roles as references to
 * the ramp stop they were chosen from, shadows, durations and easing curves
 * as their own types, and typography roles as composites. Gradients are CSS
 * strings the format cannot express, so they travel in the `com.kernic`
 * extension, as does the prose measure (`ch` is not a format unit).
 */
export function dtcgTokens(ds: DesignSystem): string {
  const color: Record<string, unknown> = {};
  for (const [rampName, ramp] of Object.entries(ds.colors) as [string, Ramp][]) {
    color[rampName] = Object.fromEntries(Object.entries(ramp).map(([stop, hex]) => [stop, dtcgColor(hex)]));
  }
  const semantic = (mode: "light" | "dark") =>
    Object.fromEntries(
      semanticEntries(ds).map((e) => {
        const hex = e[mode];
        const at = findRampStop(ds, hex);
        return [e.css, at ? dtcgAlias("color", `color.${at.ramp}.${at.stop}`) : dtcgColor(hex)];
      })
    );
  color.semantic = { light: semantic("light"), dark: semantic("dark") };

  const t = ds.typography;
  const sizes = Object.fromEntries(typeScaleEntries(ds)) as Record<TypeStep, string>;
  const roles = Object.fromEntries(
    TYPE_ROLES.map((role) => [
      role.name,
      {
        $type: "typography",
        $value: {
          fontFamily: `{font.${role.font}}`,
          fontSize: `{typography.size.${role.step}}`,
          fontWeight: `{typography.weight.${role.weight}}`,
          letterSpacing: `{typography.tracking.${role.tracking}}`,
          lineHeight: `{typography.leading.${role.step}}`,
        },
      },
    ])
  );

  const extension: Record<string, unknown> = {
    generator: "kernic",
    name: ds.name,
    vibe: ds.vibe,
    schemaVersion: ds.schemaVersion,
    format: "2025.10",
    measure: ds.containers.measure,
  };
  if (ds.gradients && Object.keys(ds.gradients).length > 0) extension.gradients = ds.gradients;

  return (
    JSON.stringify(
      {
        color,
        font: {
          heading: { $type: "fontFamily", $value: [ds.fonts.heading] },
          body: { $type: "fontFamily", $value: [ds.fonts.body] },
          mono: { $type: "fontFamily", $value: [ds.fonts.mono] },
        },
        radius: Object.fromEntries((["sm", "md", "lg", "xl"] as const).map((k) => [k, dtcgDimension(ds.radius[k])])),
        typography: {
          size: Object.fromEntries(typeScaleEntries(ds).map(([name, rem]) => [name, dtcgDimension(`${rem}rem`)])),
          leading: Object.fromEntries(TYPE_STEPS.map((s) => [s, { $type: "number", $value: t.leading[s] }])),
          weight: Object.fromEntries(Object.entries(t.weights).map(([k, v]) => [k, { $type: "fontWeight", $value: v }])),
          tracking: Object.fromEntries(Object.entries(t.tracking).map(([k, v]) => [k, dtcgDimension(v)])),
          ...roles,
        },
        spacing: {
          unit: dtcgDimension(ds.spacing.unit),
          ...Object.fromEntries(Object.entries(ds.spacing.scale).map(([k, v]) => [k, dtcgDimension(v)])),
        },
        shadow: {
          light: Object.fromEntries(SHADOW_LEVELS.map((l) => [l, dtcgShadow(ds.shadows[l].light)])),
          dark: Object.fromEntries(SHADOW_LEVELS.map((l) => [l, dtcgShadow(ds.shadows[l].dark)])),
        },
        motion: {
          duration: Object.fromEntries(Object.entries(ds.motion.duration).map(([k, v]) => [k, dtcgDuration(v)])),
          ease: Object.fromEntries(Object.entries(ds.motion.ease).map(([k, v]) => [k, { $type: "cubicBezier", $value: v }])),
        },
        breakpoint: Object.fromEntries(Object.entries(ds.breakpoints).map(([k, v]) => [k, dtcgDimension(v)])),
        container: Object.fromEntries(
          Object.entries(ds.containers)
            .filter(([k]) => k !== "measure")
            .map(([k, v]) => [k, dtcgDimension(v)])
        ),
        $extensions: { "com.kernic": extension },
      },
      null,
      2
    ) + "\n"
  );
}
